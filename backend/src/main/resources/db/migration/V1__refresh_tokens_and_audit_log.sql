-- Refresh tokens: long-lived, single-use, revocable. We store only a SHA-256 hash of the token,
-- so a database leak does not leak usable tokens (same idea as storing password hashes).
CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash  VARCHAR(64)              NOT NULL UNIQUE,
    -- All tokens from one login share a family; reuse of an old one revokes the whole family.
    family_id   VARCHAR(36)              NOT NULL,
    user_id     BIGINT                   NOT NULL,
    username    VARCHAR(100)             NOT NULL,
    issued_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at  TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens (family_id);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);

-- Audit log: one row per state-changing action, successful or not.
CREATE TABLE audit_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    username     VARCHAR(100),
    user_id      BIGINT,
    staff_id     BIGINT,
    office_id    BIGINT,
    action       VARCHAR(40)              NOT NULL,
    client_id    BIGINT,
    loan_id      BIGINT,
    amount       NUMERIC(19, 2),
    outcome      VARCHAR(20)              NOT NULL,
    detail       VARCHAR(1000)
);
CREATE INDEX idx_audit_log_loan ON audit_log (loan_id);
CREATE INDEX idx_audit_log_client ON audit_log (client_id);
CREATE INDEX idx_audit_log_occurred ON audit_log (occurred_at);
