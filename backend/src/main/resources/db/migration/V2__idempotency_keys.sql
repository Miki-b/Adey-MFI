-- V2: Idempotency-Key support. One row per (user, key): the request fingerprint and the stored
-- response, so a retried request returns the first answer instead of running twice.
CREATE TABLE idempotency_keys (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR(100)             NOT NULL,
    idem_key         VARCHAR(100)             NOT NULL,
    -- e.g. "POST /api/loans/1/repayments"
    endpoint         VARCHAR(200)             NOT NULL,
    -- SHA-256 of endpoint + request body: the same key with a different body is refused (422)
    request_hash     VARCHAR(64)              NOT NULL,
    -- IN_PROGRESS while the first request runs, COMPLETED with the response, or OUTCOME_UNKNOWN
    state            VARCHAR(20)              NOT NULL,
    response_body    TEXT,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_idempotency_user_key UNIQUE (username, idem_key)
);
CREATE INDEX idx_idempotency_expires ON idempotency_keys (expires_at);
