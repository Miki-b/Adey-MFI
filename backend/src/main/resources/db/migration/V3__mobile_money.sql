-- V3: mobile money repayments (Phase 5).

-- A request to collect money from a client's phone wallet, and where it is in its life.
CREATE TABLE payment_intents (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Our reference, sent to the provider and echoed back in its webhook and settlements.
    reference               VARCHAR(40)              NOT NULL UNIQUE,
    loan_id                 BIGINT                   NOT NULL,
    client_id               BIGINT                   NOT NULL,
    office_id               BIGINT                   NOT NULL,
    requested_by            VARCHAR(100)             NOT NULL,
    phone                   VARCHAR(20)              NOT NULL,
    amount                  NUMERIC(19, 2)           NOT NULL,
    currency                VARCHAR(3)               NOT NULL,
    -- PENDING, DECLINED, CHARGE_FAILED, MISMATCH, RECEIVED, RETRYING, POSTED, NEEDS_ATTENTION
    status                  VARCHAR(20)              NOT NULL,
    provider_charge_id      VARCHAR(60) UNIQUE,
    -- The provider's id for the money movement; becomes the Fineract receipt number.
    provider_transaction_id VARCHAR(60) UNIQUE,
    provider_amount         NUMERIC(19, 2),
    paid_at                 TIMESTAMP WITH TIME ZONE,
    fineract_transaction_id BIGINT,
    posting_attempts        INT                      NOT NULL DEFAULT 0,
    next_attempt_at         TIMESTAMP WITH TIME ZONE,
    last_error              VARCHAR(1000),
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Optimistic locking: two workers can never both move the same intent forward.
    version                 BIGINT                   NOT NULL DEFAULT 0
);
CREATE INDEX idx_payment_intents_loan ON payment_intents (loan_id);
CREATE INDEX idx_payment_intents_due ON payment_intents (status, next_attempt_at);

-- Every state change of an intent, with its time (the intent's history).
CREATE TABLE payment_intent_transitions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intent_id   BIGINT                   NOT NULL REFERENCES payment_intents (id),
    from_status VARCHAR(20),
    to_status   VARCHAR(20)              NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    note        VARCHAR(1000)
);
CREATE INDEX idx_payment_transitions_intent ON payment_intent_transitions (intent_id);

-- Inbox: every webhook whose signature and timestamp were valid, stored BEFORE we act on it.
-- event_id is unique, so a provider re-delivering the same event changes nothing.
CREATE TABLE webhook_events (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id                VARCHAR(80)              NOT NULL UNIQUE,
    charge_id               VARCHAR(60),
    reference               VARCHAR(40),
    status                  VARCHAR(20),
    amount                  NUMERIC(19, 2),
    currency                VARCHAR(3),
    provider_transaction_id VARCHAR(60),
    event_timestamp         TIMESTAMP WITH TIME ZONE,
    received_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    -- ACCEPTED, MISMATCH, UNKNOWN_REFERENCE, IGNORED
    outcome                 VARCHAR(20)              NOT NULL,
    outcome_detail          VARCHAR(1000),
    intent_id               BIGINT,
    raw_body                TEXT                     NOT NULL
);

-- Reconciliation: one run per execution, findings per difference (or match).
CREATE TABLE reconciliation_runs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_date     DATE                     NOT NULL,
    triggered_by      VARCHAR(100)             NOT NULL,
    started_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at       TIMESTAMP WITH TIME ZONE,
    provider_count    INT,
    provider_total    NUMERIC(19, 2),
    fineract_count    INT,
    fineract_total    NUMERIC(19, 2),
    status            VARCHAR(20)              NOT NULL,
    error             VARCHAR(1000)
);
CREATE INDEX idx_reconciliation_runs_date ON reconciliation_runs (business_date);

CREATE TABLE reconciliation_findings (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                  BIGINT                   NOT NULL REFERENCES reconciliation_runs (id),
    -- MATCHED, PAID_NOT_POSTED, POSTED_NOT_PAID, AMOUNT_MISMATCH
    finding_type            VARCHAR(20)              NOT NULL,
    office_id               BIGINT,
    loan_id                 BIGINT,
    intent_id               BIGINT,
    reference               VARCHAR(40),
    receipt_number          VARCHAR(60),
    provider_amount         NUMERIC(19, 2),
    provider_paid_at        TIMESTAMP WITH TIME ZONE,
    intent_amount           NUMERIC(19, 2),
    fineract_amount         NUMERIC(19, 2),
    fineract_transaction_id BIGINT,
    detail                  VARCHAR(1000),
    resolved_at             TIMESTAMP WITH TIME ZONE,
    resolved_by             VARCHAR(100),
    resolution_note         VARCHAR(1000)
);
CREATE INDEX idx_reconciliation_findings_run ON reconciliation_findings (run_id);
